#!/usr/bin/env bash
# Generate per-directory git identities from ~/.config/dotfiles/identities.conf:
#   ~/<dir>/.gitconfig     name, email, auth key, signing key, signing on
#                          (keys are used via ssh-agent; only .pub files on disk)
#   ~/.gitconfig.local     includeIf "gitdir:~/<dir>/" for each identity
#   ~/.ssh/allowed_signers so `git log --show-signature` verifies
# ssh-unlock runs this after loading keys; run it by hand after editing the
# identities file.
#
#   git-identities.sh          apply identities.conf; identities removed or
#                              commented out since the last run are cleaned up
#   git-identities.sh --clean  remove every identity this script set up
#
# Cleaning up an identity deletes its ~/<dir>/.gitconfig (and ~/<dir> if
# empty), its ~/.ssh/<key>.pub files, and drops its keys from ssh-agent.
# Keys still used by a remaining identity are kept.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

local_cfg="$HOME/.gitconfig.local"
signers="$HOME/.ssh/allowed_signers"
# What the last run applied, so removed identities can be cleaned up.
applied="$HOME/.config/dotfiles/identities.applied"
mkdir -p "$HOME/.ssh" "$(dirname "$applied")"

if [[ ${1:-} == --clean ]]; then
  identities=""
else
  identities="$(read_identities)"
fi

# Clean up identities that were applied before but aren't wanted now.
if [[ -f $applied ]]; then
  wanted_dirs=" $(cut -d'|' -f1 <<<"$identities" | tr '\n' ' ') "
  wanted_keys=" $(cut -d'|' -f4,5 <<<"$identities" | tr '|\n' '  ') "
  while IFS='|' read -r dir _ email auth sign; do
    [[ -n $dir && $wanted_dirs != *" $dir "* ]] || continue
    cfg="$HOME/$dir/.gitconfig"
    if grep -q '^# Generated by ~/dotfiles/scripts/git-identities.sh' "$cfg" 2>/dev/null; then
      rm -f "$cfg"
    fi
    rmdir "$HOME/$dir" 2>/dev/null || true
    for key in "$auth" "$sign"; do
      [[ $wanted_keys != *" $key "* && -f $HOME/.ssh/$key.pub ]] || continue
      ssh-add -d "$HOME/.ssh/$key.pub" >/dev/null 2>&1 || true
      rm -f "$HOME/.ssh/$key.pub"
    done
    log "removed identity ~/$dir ($email)"
  done <"$applied"
fi

: >"$signers"

# Drop previously generated includeIf blocks, keep anything hand-written.
if [[ -f $local_cfg ]]; then
  sed -i.bak '/^# >>> git-identities/,/^# <<< git-identities/d' "$local_cfg" && rm -f "$local_cfg.bak"
fi
echo "# >>> git-identities (generated by ~/dotfiles/scripts/git-identities.sh)" >>"$local_cfg"

while IFS='|' read -r dir name email auth sign; do
  [[ -n $dir ]] || continue

  mkdir -p "$HOME/$dir"
  cat >"$HOME/$dir/.gitconfig" <<CFG
# Generated by ~/dotfiles/scripts/git-identities.sh — edit ~/.config/dotfiles/identities.conf instead.
[user]
	name = $name
	email = $email
	signingkey = $HOME/.ssh/$sign.pub
[core]
	sshCommand = ssh -i ~/.ssh/$auth -o IdentitiesOnly=yes
[commit]
	gpgsign = true
[tag]
	gpgsign = true
CFG
  printf '[includeIf "gitdir:~/%s/"]\n\tpath = ~/%s/.gitconfig\n' "$dir" "$dir" >>"$local_cfg"

  if [[ -f $HOME/.ssh/$sign.pub ]]; then
    echo "$email namespaces=\"git\" $(cut -d' ' -f1,2 "$HOME/.ssh/$sign.pub")" >>"$signers"
  else
    warn "~/.ssh/$sign.pub missing; run scripts/ssh-unlock.sh"
  fi
  log "identity ~/$dir -> $email"
done <<<"$identities"

echo "# <<< git-identities" >>"$local_cfg"
printf '%s\n' "$identities" >"$applied"
