#!/usr/bin/env bash
# Generate per-directory git identities from ~/.config/dotfiles/identities.conf:
#   ~/<dir>/.gitconfig     name, email, auth key, signing key, signing on
#                          (keys are used via ssh-agent; only .pub files on disk)
#   ~/.gitconfig.local     includeIf "gitdir:~/<dir>/" for each identity
#   ~/.ssh/allowed_signers so `git log --show-signature` verifies
# Run after scripts/ssh-unlock.sh so the public keys exist.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

local_cfg="$HOME/.gitconfig.local"
signers="$HOME/.ssh/allowed_signers"
mkdir -p "$HOME/.ssh"
: >"$signers"

# Drop previously generated includeIf blocks, keep anything hand-written.
if [[ -f $local_cfg ]]; then
  sed -i.bak '/^# >>> git-identities/,/^# <<< git-identities/d' "$local_cfg" && rm -f "$local_cfg.bak"
fi
echo "# >>> git-identities (generated by ~/dotfiles/scripts/git-identities.sh)" >>"$local_cfg"

identities="$(read_identities)"
while IFS='|' read -r dir name email auth sign; do
  [[ -n $dir ]] || continue

  mkdir -p "$HOME/$dir"
  cat >"$HOME/$dir/.gitconfig" <<CFG
# Generated by ~/dotfiles/scripts/git-identities.sh — edit ~/.config/dotfiles/identities.conf instead.
[user]
	name = $name
	email = $email
	signingkey = $HOME/.ssh/$sign.pub
[core]
	sshCommand = ssh -i ~/.ssh/$auth -o IdentitiesOnly=yes
[commit]
	gpgsign = true
[tag]
	gpgsign = true
CFG
  printf '[includeIf "gitdir:~/%s/"]\n\tpath = ~/%s/.gitconfig\n' "$dir" "$dir" >>"$local_cfg"

  if [[ -f $HOME/.ssh/$sign.pub ]]; then
    echo "$email namespaces=\"git\" $(cut -d' ' -f1,2 "$HOME/.ssh/$sign.pub")" >>"$signers"
  else
    warn "~/.ssh/$sign.pub missing; run scripts/ssh-unlock.sh"
  fi
  log "identity ~/$dir -> $email"
done <<<"$identities"

echo "# <<< git-identities" >>"$local_cfg"
